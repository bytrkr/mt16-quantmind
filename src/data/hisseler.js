/**
 * Alpaca ve Canlı Ağ Geçidi Fiyat Senkronizasyonu.
 * Qodi Kuralı: Fiyat yoksa asla varsayılan atanmaz, null kalır.
 */
export function updateHisselerFromAlpaca(priceMap) {
  if (!priceMap) return;

  for (const [symbol, data] of Object.entries(priceMap)) {
    const cleanCode = symbol.replace(/\.IS$/i, '');
    const priceVal = data.price !== undefined ? data.price : null;
    const statusVal = data.status || (priceVal !== null ? 'VERİ_VAR' : 'İŞLEM DURDURULDU (VERİ YOK)');

    const record = {
      kod: cleanCode,
      fiyat: priceVal,
      degisim: data.rate !== undefined ? data.rate : (data.degisim !== undefined ? data.degisim : null),
      status: statusVal,
      guncellemeZamani: new Date().toISOString()
    };

    if (HISSELER[cleanCode]) {
      Object.assign(HISSELER[cleanCode], record);
    } else {
      HISSELER[cleanCode] = record;
      HISSELER[cleanCode + '.IS'] = HISSELER[cleanCode];
    }
  }
}

/**
 * Hisse koduna göre veri döndürür.
 * Qodi Kuralı: Hisse bulunamazsa veya verisi eksikse 'VERİ YOK' döner.
 */
export function getHisse(symbol) {
  if (!symbol) {
    return { kod: 'VERİ YOK', ad: 'VERİ YOK', fiyat: null, degisim: null, status: 'VERİ YOK' };
  }
  const cleanCode = String(symbol).replace(/\.IS$/i, '').toUpperCase().trim();
  const found = HISSELER[cleanCode] || HISSELER[symbol];
  if (!found) {
    return { kod: cleanCode, ad: 'VERİ YOK', fiyat: null, degisim: null, status: 'VERİ YOK' };
  }
  return found;
}

